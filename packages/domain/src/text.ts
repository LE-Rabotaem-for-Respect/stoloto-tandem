// Символы, которые не видны или меняют показ соседнего текста: управляющие (Cc),
// форматирующие (Cf: U+200B, U+202E, U+2063, теги U+E0000–E007F), разделители
// строк и абзацев (U+2028, U+2029), всё, что Unicode не показывает
// (Default_Ignorable: заполнители хангыля U+3164, U+FFA0, U+034F), неназначенные (Cn,
// в том числе несимволы U+FFFE, U+10FFFF), частные (Co), суррогатные половины (Cs),
// заполнитель U+16FE4 и пустой символ Брайля U+2800.
// Ими переворачивают текст в ленте, прячут строку или делают двойника чужого названия.
const HIDDEN = String.raw`\p{Cc}\p{Cf}\p{Zl}\p{Zp}\p{DI}\p{Cn}\p{Co}\p{Cs}\u{16FE4}\u{2800}`;
// Из невидимых разрешены только те, что приходят при обычном вводе и копировании, и
// только на своём месте — иначе ими склеивают слово, которое потом не находится поиском:
// - соединитель U+200D — между эмодзи (после тона кожи или селектора), как в «бегунье»;
// - селекторы начертания U+FE00–FE0F — сразу после эмодзи, цифры в keycap или ©;
// - мягкий перенос U+00AD — между буквами слова.
const ZWJ = String.raw`(?<=\p{Extended_Pictographic}(?:\u{FE0F}|[\u{1F3FB}-\u{1F3FF}])?)\u{200D}(?=\p{Extended_Pictographic})`;
const SELECTOR = String.raw`(?<=\p{Emoji})[\u{FE00}-\u{FE0F}]`;
const SOFT_HYPHEN = String.raw`(?<=\p{L}\p{M}*)\u{AD}(?=\p{L})`;
const ALLOWED = `${ZWJ}|${SELECTOR}|${SOFT_HYPHEN}`;
// В многострочном тексте — ещё перевод строки и табуляция
const LINE_BREAKS = String.raw`[\n\t]`;

/**
 * Однострочный текст пользователя (название, город, адрес, поисковый запрос):
 * без невидимых символов, кроме разрешённых. Общее для api и web, чтобы проверки
 * формы совпадали с серверными.
 */
export const SINGLE_LINE_TEXT = new RegExp(`^(?:[^${HIDDEN}]|${ALLOWED})*$`, 'u');

/** Многострочный текст (описание, вопрос к заявке). */
export const MULTI_LINE_TEXT = new RegExp(`^(?:[^${HIDDEN}]|${ALLOWED}|${LINE_BREAKS})*$`, 'u');

/**
 * В названии, городе, месте есть хотя бы одна буква или цифра: строка из точек, тире
 * или одних эмодзи на карточке выглядит пустой.
 */
export const VISIBLE_TEXT = /[\p{L}\p{N}]/u;

/**
 * Однострочный текст перед проверкой: без пробелов по краям и без мягких переносов —
 * в коротком поле они не нужны, а слово с ними не находится поиском.
 */
export function cleanSingleLine(text: string): string {
  return text.replaceAll('­', '').trim();
}

/** Переводы строк Windows и старых Mac (`\r\n`, `\r`) — к одному `\n`. */
export function normalizeLineBreaks(text: string): string {
  return text.replace(/\r\n?/g, '\n');
}
